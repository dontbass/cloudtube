import 'package:cloudtube/channels/models/channel.dart';
import 'package:cloudtube/utils/views/components/thumbnail.dart';
import 'package:flutter/material.dart';
import 'package:flutter_linkify/flutter_linkify.dart';
import 'package:intl/intl.dart';
import 'package:url_launcher/url_launcher.dart';

import '../../../cloudtube/theme.dart';
import '../../../utils/models/image_object.dart';

/// Вкладка «О канале»: баннер, описание со ссылками, сведения.
class ChannelInfo extends StatelessWidget {
  final Channel channel;

  const ChannelInfo({super.key, required this.channel});

  @override
  Widget build(BuildContext context) {
    final colors = Theme.of(context).colorScheme;
    final text = Theme.of(context).textTheme;
    final banner = ImageObject.getBestThumbnail(channel.authorBanners)?.url;
    final facts = <(IconData, String)>[
      if ((channel.totalViews ?? 0) > 0)
        (Icons.visibility_outlined, '${NumberFormat.decimalPattern('ru').format(channel.totalViews)} просмотров'),
      if ((channel.joined ?? 0) > 0)
        (
          Icons.calendar_today_outlined,
          'На YouTube с ${DateFormat('dd.MM.yyyy').format(DateTime.fromMillisecondsSinceEpoch(channel.joined! * 1000))}'
        ),
      if (channel.autoGenerated) (Icons.smart_toy_outlined, 'Канал создан YouTube автоматически'),
    ];

    return ListView(padding: const EdgeInsets.fromLTRB(16, 12, 16, 24), children: [
      if (banner != null)
        AspectRatio(
          aspectRatio: 6.2,
          child: Thumbnail(
              width: double.infinity,
              thumbnails: [banner],
              decoration:
                  BoxDecoration(color: colors.secondaryContainer, borderRadius: BorderRadius.circular(14))),
        ),
      if (channel.description.trim().isNotEmpty)
        Container(
          margin: const EdgeInsets.only(top: 12),
          padding: const EdgeInsets.all(14),
          decoration: BoxDecoration(color: colors.surfaceContainerHigh, borderRadius: BorderRadius.circular(18)),
          child: SelectableLinkify(
              text: channel.description.trim(),
              style: text.bodyMedium,
              linkStyle: TextStyle(color: ctAccent(colors), decoration: TextDecoration.none),
              onOpen: (link) => launchUrl(Uri.parse(link.url), mode: LaunchMode.externalApplication),
              options: const LinkifyOptions(humanize: true, removeWww: true)),
        ),
      for (final f in facts)
        Padding(
          padding: const EdgeInsets.only(top: 12, left: 4),
          child: Row(children: [
            Icon(f.$1, size: 20, color: colors.onSurfaceVariant),
            const SizedBox(width: 12),
            Expanded(child: Text(f.$2, style: text.bodyMedium?.copyWith(color: colors.onSurfaceVariant))),
          ]),
        ),
      if (banner == null && channel.description.trim().isEmpty && facts.isEmpty)
        Padding(
          padding: const EdgeInsets.only(top: 40),
          child: Text('Автор не добавил описание',
              textAlign: TextAlign.center, style: text.bodyLarge?.copyWith(color: colors.onSurfaceVariant)),
        ),
    ]);
  }
}
